interface Skill {
  id: string
  desc: string      // 自然语言描述，用于语义检索
  code: string      // 可执行代码
  uses: number      // 被调用次数
  ok: number        // 调用成功次数
}

async function solve(task: string, lib: Skill[], env: Env): Promise<'reused' | 'learned' | 'failed'> {
  // ① 检索：按描述语义找最相近的已有技能，能拼出来就直接用
  const hit = await lib.findRelevant(task, 3)
  if (hit.length > 0 && (await env.tryCompose(hit, task))) return 'reused'

  // ② 生成：把检索到的相似技能当 few-shot，写出新技能
  let code = await generate(task, hit)

  // ③ 验证：在真实环境里跑，失败就把报错喂回去重写（最多三轮）
  let passed = false
  for (let attempt = 0; attempt < 3; attempt++) {
    const run = await env.exec(code)
    if (run.ok && (await env.checkGoal(task))) {      // 跑通 ≠ 达成目标，两个都要
      passed = true
      break
    }
    code = await revise(code, run.error ?? '目标未达成', task)
  }
  if (!passed) return 'failed'

  // ④ 入库：描述要写「什么时候该用它」，不只是「它做了什么」
  lib.push({
    id: hash(code),
    desc: await describeSkill(task, code),
    code,
    uses: 0,
    ok: 0,
  })
  return 'learned'
}
