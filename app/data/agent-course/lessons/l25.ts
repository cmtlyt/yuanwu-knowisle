async function selfConsistency(problem: string, k = 5): Promise<string> {
  // ① 采样：温度必须大于 0，否则 k 条链彼此相同，投票毫无意义
  const chains = await Promise.all(
    Array.from({ length: k }, () => chainOfThought(problem, { temperature: 0.7 })),
  )

  // ② 抽取 + 归一化：把「$1,200」「1200 元」「1.2k」统一成同一个可比形式
  const keys = chains.map((c) => normalize(extractAnswer(c)))

  // ③ 投票：取众数；票数相同时取「更早出现」的那个（稳定，不引入额外模型调用）
  const tally = new Map<string, number>()
  for (const key of keys) tally.set(key, (tally.get(key) ?? 0) + 1)
  let best = keys[0]
  for (const [key, n] of tally) if (n > (tally.get(best) ?? 0)) best = key
  return best
}

// 归一化：这一步决定了整个方法的成败
function normalize(raw: string): string {
  const s = raw.trim().toLowerCase()
  const num = s.replace(/[,$\\s]/g, '').match(/-?\\d+(?:\\.\\d+)?/)
  if (num) return String(Number(num[0]))          // 数字统一成最简形式：1,200 → 1200，1.20 → 1.2
  return s.replace(/[。.!！?？\\s]/g, '')          // 文本答案去标点空白，再比
}
