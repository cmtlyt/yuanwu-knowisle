加权投票有个反直觉的陷阱：**置信度高的错误答案会压倒数量多的正确答案**。如果一个样本说「62%，我确定」而另外两个说「40%，不太确定」但结论一致，加权会把错误答案选出来。所以加权只在「置信度确实校准过」时可靠——多数模型的自报置信度并不可靠。

实践建议：**默认用等权多数票**，加权作为实验性优化，并用固定样本集验证它确实更好。

